"""
Tests for ConsensusCore - the main facade for consensus operations.

This test suite verifies the ConsensusCore class which provides the primary
interface for creating and managing consensus instances.
"""

from typing import Any, Type
from unittest.mock import AsyncMock, MagicMock

import pytest
from pydantic import BaseModel, Field

from blockether_catalyst.consensus.Consensus import Consensus
from blockether_catalyst.consensus.ConsensusCore import ConsensusCore
from blockether_catalyst.consensus.ConsensusTypes import (
    ConsensusSettings,
    ModelConfiguration,
)
from blockether_catalyst.consensus.VotingComparison import (
    BaseModelWithReasoning,
    ComparisonStrategy,
    VotingField,
)
from blockether_catalyst.utils.TypedCalls import ArityOneTypedCall


class ConsensusTestResponse(BaseModelWithReasoning):
    """Test response model that extends BaseModelWithReasoning."""

    answer: str = VotingField(
        description="The answer",
        comparison=ComparisonStrategy.EXACT,  # Exact match for testing
    )
    confidence: float = VotingField(
        default=0.9,
        description="Confidence level",
        comparison=ComparisonStrategy.RANGE,
        tolerance=0.1,  # Allow 10% variance
    )


class MockTypedCall(ArityOneTypedCall[str, ConsensusTestResponse]):
    """Mock typed call for testing."""

    def __init__(self, answer: str = "deterministic_answer", confidence: float = 0.95) -> None:
        """Initialize mock with deterministic response."""
        self._answer = answer
        self._confidence = confidence

    async def call(self, x: str) -> ConsensusTestResponse:
        """Return deterministic response."""
        return ConsensusTestResponse(
            answer=self._answer,
            confidence=self._confidence,
            reasoning=f"Deterministic response: {self._answer} with confidence {self._confidence} for input: {x}. This response is generated by a deterministic mock model that always returns the same predetermined values for consistent testing. The reasoning includes detailed explanation of the mock behavior and validation of input processing to meet minimum character requirements for proper consensus validation.",
        )


class TestConsensusCore:
    """Test suite for ConsensusCore facade."""

    @pytest.fixture
    def core(self) -> Any:
        """Create ConsensusCore instance."""
        return ConsensusCore()

    @pytest.fixture
    def mock_executor(self) -> Any:
        """Create mock typed call."""
        return MockTypedCall(answer="test_answer", confidence=0.90)

    @pytest.fixture
    def test_initialization(self, core: Any) -> None:
        """Test ConsensusCore initialization."""
        assert isinstance(core, ConsensusCore)

    def test_consensus_default(self, core: Any, mock_executor: Any) -> None:
        """Test creating Consensus with defaults."""
        models = [
            core.model(
                id="test-model-1",
                executor=mock_executor,
                perspective="As test model 1",
            ),
            core.model(
                id="test-model-2",
                executor=mock_executor,
                perspective="As test model 2",
            ),
            core.model(
                id="test-model-3",
                executor=mock_executor,
                perspective="As test model 3",
            ),
        ]
        judge = mock_executor  # Use same executor as judge
        consensus = core.consensus(models=models, judge=judge)

        assert consensus.__class__.__name__ == "Consensus"
        assert consensus.settings.max_rounds == 5
        assert consensus.settings.threshold == 0.5
        # First round threshold is auto-adjusted for 3 models (max is 0.667)
        assert consensus.settings.first_round_threshold < 0.667
        assert consensus.settings.max_concurrent_calls == 10

