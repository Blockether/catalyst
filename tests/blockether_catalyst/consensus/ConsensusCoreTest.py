    def test_create_consensus_request_removed(self, core: Any, mock_executor: Any) -> None:
        """Test that consensus request creation was simplified."""
        models = [core.model(id=f"model-{i}", executor=mock_executor, perspective=f"As model {i}") for i in range(3)]

        # ConsensusRequest was removed - consensus is now directly created
        from blockether_catalyst.consensus.ConsensusTypes import ConsensusSettings

        settings = ConsensusSettings(max_rounds=3)
        judge = mock_executor  # Use same executor as judge
        consensus = core.consensus(models=models, judge=judge, settings=settings)

        assert consensus.__class__.__name__ == "Consensus"
        assert len(consensus.models) == 3
        assert consensus.models[0].id == "model-0"
        assert consensus.models[1].id == "model-1"
        assert consensus.models[2].id == "model-2"
        assert consensus.settings.max_rounds == 3

    @pytest.mark.anyio
    async def test_full_consensus_workflow(self, core: Any) -> None:
        """Test complete consensus workflow using ConsensusCore with deterministic models."""
        # Create deterministic models that all return the same answer for consensus
        deterministic_executor = MockTypedCall(answer="life_meaning_42", confidence=0.98)
        judge_executor = MockTypedCall(answer="life_meaning_42", confidence=0.99)

        models = [
            core.model(
                id=f"model-{i}",
                executor=deterministic_executor,
                perspective=f"As model {i}",
                weight_multiplier=1.0 - (i * 0.1),
            )
            for i in range(3)
        ]

        # Create and execute consensus directly
        from blockether_catalyst.consensus.ConsensusTypes import ConsensusSettings

        settings = ConsensusSettings(max_rounds=3)
        consensus = core.consensus(models=models, judge=judge_executor, settings=settings)
        result = await consensus.call("What is the meaning of life?")

        # Strong exact assertions
        assert result.consensus_achieved is True
        assert result.total_rounds == 1
        assert len(result.participating_models) == 3
        assert result.final_response.__class__.__name__ == "ConsensusTestResponse"
        assert result.final_response.answer == "life_meaning_42"
        assert result.final_response.confidence == 0.98

    def test_static_methods_are_static(self) -> None:
        """Test that static methods work without instance."""
        # Create mock typed call
        mock_call = MockTypedCall(answer="static_test_answer", confidence=0.96)

        # Test static method without instance
        config1 = ConsensusCore.model(id="static-test-1", executor=mock_call, perspective="As static test 1")
        config2 = ConsensusCore.model(id="static-test-2", executor=mock_call, perspective="As static test 2")
        config3 = ConsensusCore.model(id="static-test-3", executor=mock_call, perspective="As static test 3")
        assert config1.id == "static-test-1"
        assert config1.perspective == "As static test 1"
        assert config1.weight_multiplier == 1.0

        consensus = ConsensusCore.consensus(models=[config1, config2, config3], judge=mock_call)
        assert consensus.__class__.__name__ == "Consensus"
        assert len(consensus.models) == 3
        assert consensus.models[0].id == "static-test-1"
        assert consensus.models[1].id == "static-test-2"
        assert consensus.models[2].id == "static-test-3"

    def test_type_annotations(self, core: Any) -> None:
        """Test that all methods have proper type annotations."""
        # This test verifies that the methods are properly typed
        # by checking their signatures
        import inspect

        # Check consensus
        sig = inspect.signature(core.consensus)
        # The return type is actually Consensus[T] (generic), not just Consensus
        assert "Consensus" in str(sig.return_annotation)

        # Check configuration
        sig = inspect.signature(core.model)
        # The return type is actually ModelConfiguration[T] (generic), not just ModelConfiguration
        assert "ModelConfiguration" in str(sig.return_annotation)

        # create_consensus_request was removed - check that it doesn't exist
        assert not hasattr(core, "create_consensus_request")
